#!/usr/bin/env python3
"""build-prompts.py — expand {{include:...}} directives into flat prompt files.

Single source of truth for ronzz.ORG prompts lives in `src/` (scenario prompts)
and `src/fundamentals/` (shared behaviour fragments). Scenario prompts pull in
fragments via include directives, so a rule is written once and updated in
exactly one place.

Include paths are relative to `src/fundamentals/` and the `.md` extension is
added automatically:

    {{include:do-not-guess}}        # -> src/fundamentals/do-not-guess.md
    {{include:wikibase/wikirules}}  # -> src/fundamentals/wikibase/wikirules.md

The build expands those directives and writes a flat, self-contained prompt
into `dist/`, mirroring `src/` with a `.prompt.md` suffix.

`src/opencode/` is a second tree: it is built into `dist/opencode/` with exact
filenames (AGENTS.md, agents/*.md, opencode.jsonc, plugins/…) so the output can
be symlinked as `~/.config/opencode`. Markdown there is include-expanded (no
generated header — agent files must start with frontmatter); other files are
copied verbatim.

HTML comments (<!-- … -->) in any source file are for contributors only: they
are stripped pre-expansion from every tree and never reach dist/ (fenced
`<!-- -->` examples are preserved). The only comment in dist/ is the generated
prompt-tree header — a no-edit-here reminder for humans browsing the outputs.

Markdown is auto-formatted when a source file is read, before include
expansion: trailing whitespace is stripped, blank-line runs collapse to a
single blank line, and (prompt tree only) list nesting is normalized to
2-space steps while stray leading whitespace on non-structural lines is
dedented. Fenced code blocks and YAML frontmatter are preserved verbatim.
`src/opencode/` markdown keeps its indentation byte-for-byte: YAML
frontmatter and minified lines there are semantically meaningful.

Usage:
    python3 build-prompts.py            rebuild all prompts into dist/
    python3 build-prompts.py --check    exit 1 if any dist/ file is stale
    python3 build-prompts.py -f Help    rebuild only matching source files
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"
FUNDAMENTALS = SRC / "fundamentals"
DIST = ROOT / "dist"
# Config tree: src/opencode/ is built into dist/opencode/ with exact filenames
# (no .prompt.md suffix, no generated header) so the output can be symlinked
# directly as ~/.config/opencode. Markdown files are include-expanded;
# everything else (jsonc, ts, mjs, json, patches) is copied verbatim.
CONFIG_SRC = SRC / "opencode"

# dist/opencode/ is a LIVE config directory once symlinked as ~/.config/opencode:
# users install node_modules there and keep API keys in .secrets/. Those are
# runtime state, not build output — the orphan pruner must never delete or
# report them. Extend this set when a new runtime artifact appears.
CONFIG_RUNTIME_ENTRIES = {
    "node_modules", ".secrets", "package-lock.json", "bun.lock", ".DS_Store",
}

# {{include:path/without/extension}} — expanded
INCLUDE_DIRECTIVE_RE = re.compile(r"\{\{include:([^{}]*)\}\}")
# {{!include:path/without/extension}} — literal text (escape hatch, rendered as-is)
LITERAL_DIRECTIVE_RE = re.compile(r"\{\{!include:[^{}]*\}\}")

# HTML comments in source files are for contributors; they never reach dist/.
# Stripped pre-expansion (text segments only — fenced examples stay intact).
HTML_COMMENT_RE = re.compile(r"<!--.*?-->", re.DOTALL)

# YAML frontmatter block (--- ... ---) — preserved verbatim, never formatted.
FRONTMATTER_RE = re.compile(r"\A---\n.*?\n---\n", re.DOTALL)
# Markdown list item: optional leading whitespace, bullet (-, *, +) or ordered
# marker (1., 1)), then whitespace. `\d+[.)]` mirrors CommonMark, so e.g. a
# paragraph starting "2026. ..." is treated as an ordered item, as it renders.
LIST_ITEM_RE = re.compile(r"^(\s*)([-*+]|\d+[.)])(\s+)")

MASK = "\x00INCL-LIT-{}\x00"

GENERATED_HEADER = (
    "<!-- GENERATED by build-prompts.py — edit the source files, never this file. -->\n"
    "<!-- source: {source} -->\n\n"
)


class BuildError(Exception):
    """Fatal build error: a directive could not be expanded."""


def fmt_path(p: Path) -> str:
    """Path relative to the prompt root, absolute otherwise."""
    try:
        return str(p.relative_to(ROOT))
    except ValueError:
        return str(p)


def fence_char(line: str) -> str | None:
    """Return the fence character if the line opens/closes a code fence."""
    s = line.strip()
    if len(s) >= 3 and s[0] in "`~" and all(c == s[0] for c in s[:3]):
        return s[0]
    return None


def split_segments(text: str) -> list[tuple[str, str]]:
    """Split text into ('text', ...) and ('code', ...) segments.

    Directives inside fenced code blocks are never expanded, so expansion
    only ever touches 'text' segments.
    """
    segments: list[tuple[str, str]] = []
    buf: list[str] = []
    kind = "text"
    fence: str | None = None
    for line in text.splitlines(keepends=True):
        fc = fence_char(line)
        if kind == "text":
            if fc is not None:
                segments.append(("text", "".join(buf)))
                buf = [line]
                kind = "code"
                fence = fc
            else:
                buf.append(line)
        else:  # code
            if fc == fence:
                buf.append(line)
                segments.append(("code", "".join(buf)))
                buf = []
                kind = "text"
                fence = None
            else:
                buf.append(line)
    if buf:
        segments.append((kind, "".join(buf)))
    return segments


def _normalize_text_segment(seg: str, fix_indent: bool) -> str:
    """Normalize one text segment (contains no code fences).

    - strips trailing whitespace on every line
    - drops blank lines at the segment start/end and collapses runs of
      consecutive blank lines to a single blank line
    - with fix_indent, normalizes indentation:
        * nested list items are re-indented to 2-space steps (dedenting a
          uniformly indented top-level list to column 0)
        * wrapped content of a list item is re-indented to the item's
          content column (item indent + 2)
        * blockquotes keep their '>' nesting but are dedented to column 0
        * any other line with stray leading whitespace (plain paragraphs,
          headings) is dedented — e.g. 4-space-indented paragraphs that
          CommonMark would render as indented code blocks
    """
    out: list[str] = []
    indent_stack: list[tuple[int, int]] = []  # (item indent, content column) per open level
    in_content = False            # inside a list item's wrapped content
    content_indent = 0            # indent of that content (item indent + 2)
    prev_blank = True
    for raw in seg.splitlines():
        line = raw.rstrip()
        if not line.strip():
            if prev_blank:
                continue
            prev_blank = True
            out.append("")
            continue
        prev_blank = False
        if fix_indent:
            if line.lstrip().startswith(">"):      # blockquote (incl. '> >')
                line = line.lstrip()
            else:
                m = LIST_ITEM_RE.match(line)
                if m:
                    indent = len(m.group(1))
                    # A new item is a CHILD of the current level only when
                    # indented at or past its content column (CommonMark
                    # rule); anything between parent indent and content
                    # column is a sibling, not a child.
                    while indent_stack and indent < indent_stack[-1][0]:
                        indent_stack.pop()
                    if not indent_stack:
                        indent_stack.append((indent, indent + 2))
                    elif indent == indent_stack[-1][0]:
                        pass  # sibling of the top level
                    elif indent >= indent_stack[-1][1]:
                        indent_stack.append((indent, indent + 2))
                    level = len(indent_stack) - 1
                    new_indent = level * 2
                    line = " " * new_indent + line[indent:]
                    in_content = True
                    content_indent = new_indent + 2
                elif in_content and line[:1].isspace():
                    # wrapped content of the current list item
                    line = " " * content_indent + line.lstrip()
                else:
                    # plain structural line: drop stray leading whitespace
                    line = line.lstrip()
                    in_content = False
        out.append(line)
    return "".join(l + "\n" for l in out)


def normalize_markdown(text: str, fix_indent: bool = True) -> str:
    """Auto-format markdown source before include expansion.

    Runs on the raw content of every markdown file when it is read, so prompt
    files, include fragments and config-tree markdown are all cleaned before
    compilation. See _normalize_text_segment for the per-segment rules;
    additionally:

    - fenced code blocks keep their content byte-for-byte except trailing
      whitespace stripping
    - a YAML frontmatter block (--- ... ---) is preserved verbatim
    - a blank line is kept between a text segment and a following code fence
    - the result always ends with exactly one newline

    Config-tree markdown (src/opencode/) is built with fix_indent=False:
    its indentation is semantically meaningful (YAML frontmatter, minified
    lines) and must not be touched.
    """
    frontmatter = ""
    fm = FRONTMATTER_RE.match(text)
    if fm:
        frontmatter = fm.group(0)
        text = text[fm.end():]
    parts: list[str] = []
    segments = split_segments(text)
    for i, (kind, seg) in enumerate(segments):
        if kind == "code":
            parts.append("".join(l.rstrip() + "\n" for l in seg.splitlines()))
            continue
        normalized = _normalize_text_segment(seg, fix_indent)
        next_is_code = i + 1 < len(segments) and segments[i + 1][0] == "code"
        if next_is_code and normalized and not normalized.endswith("\n\n"):
            normalized += "\n"  # keep a blank line before the code fence
        parts.append(normalized)
    return (frontmatter + "".join(parts)).rstrip("\n") + "\n"


def normalize_include_path(path: str, from_rel: Path, from_line: int) -> str:
    """Validate an include path and return it as '<dirs>/<name>' (no .md)."""
    path = path.strip()
    if path.endswith(".md"):
        path = path[:-3]
    path = path.strip()
    if not path:
        raise BuildError(f"{from_rel}:{from_line}: empty include directive")
    p = Path(path)
    if p.is_absolute():
        raise BuildError(
            f"{from_rel}:{from_line}: include path must be relative to "
            f"fundamentals/ (got absolute path {path!r})"
        )
    if ".." in p.parts:
        raise BuildError(
            f"{from_rel}:{from_line}: include path must be relative to "
            f"fundamentals/ and must not contain '..' (got {path!r})"
        )
    return path


def expand_include(path: str, from_rel: Path, from_line: int,
                   stack: tuple[Path, ...]) -> str:
    """Expand one include directive, resolving `path` under fundamentals/."""
    path = normalize_include_path(path, from_rel, from_line)
    target = (FUNDAMENTALS / f"{path}.md").resolve()
    if not target.is_relative_to(FUNDAMENTALS):
        raise BuildError(
            f"{from_rel}:{from_line}: include target escaped fundamentals/ "
            f"({fmt_path(target)})"
        )
    if not target.is_file():
        chain = " -> ".join(fmt_path(p) for p in stack)
        raise BuildError(
            f"{from_rel}:{from_line}: include not found: {path!r} "
            f"(expected at {fmt_path(target)}) [chain: {chain}]"
        )
    if target in stack:
        cycle = " -> ".join(fmt_path(p) for p in (*stack, target))
        raise BuildError(f"{from_rel}:{from_line}: include cycle: {cycle}")
    # Fragments are normalized for whitespace only (fix_indent=False): their
    # indentation is often relative to the include site — e.g. included inside
    # a list item (`- {{include:...}}`) — so it carries nesting semantics and
    # must be preserved byte-for-byte.
    text = normalize_markdown(target.read_text(encoding="utf-8"), fix_indent=False)
    return expand_text(text, target.relative_to(ROOT), (*stack, target))


def expand_text(text: str, rel: Path, stack: tuple[Path, ...]) -> str:
    """Expand directives in a text segment (no code fences inside)."""
    literals: list[str] = []

    def mask(m: re.Match[str]) -> str:
        # {{!include:x}} -> literal {{include:x}}, temporarily masked away
        literals.append(m.group(0).replace("{{!", "{{", 1))
        return MASK.format(len(literals) - 1)

    masked = LITERAL_DIRECTIVE_RE.sub(mask, text)
    out: list[str] = []
    for lineno, line in enumerate(masked.splitlines(keepends=True), start=1):
        out.append(INCLUDE_DIRECTIVE_RE.sub(
            lambda m: expand_include(m.group(1), rel, lineno, stack),
            line,
        ))
    joined = "".join(out)
    collapsed = re.sub(r"(?:\r?\n){3,}", "\n\n", joined)
    # Anything still looking like a directive (incl. whitespace variants like
    # "{{ include:... }}") was either malformed or forgot the escape hatch.
    dangling = re.search(r"\{\{\s*!?\s*include:", collapsed)
    if dangling:
        raise BuildError(
            f"{rel}: malformed include directive near "
            f"{collapsed[max(0, dangling.start() - 20):dangling.end() + 20]!r}; "
            f"syntax is {{{{include:do-not-guess}}}} — use "
            f"{{{{!include:...}}}} for literal text"
        )
    for i, literal in enumerate(literals):
        collapsed = collapsed.replace(MASK.format(i), literal)
    return collapsed


def strip_html_comments(text: str) -> str:
    """Remove HTML comments (<!-- ... -->) from a text segment.

    Comments in source files are for contributors; they must never reach the
    built output. Applied to text segments only, so `<!-- -->` examples inside
    fenced code blocks are preserved.
    """
    return HTML_COMMENT_RE.sub("", text)


def build_file(source: Path) -> str:
    """Expand a source file into its flat prompt content."""
    text = normalize_markdown(source.read_text(encoding="utf-8"))
    parts: list[str] = []
    for kind, seg in split_segments(text):
        if kind == "text":
            parts.append(expand_text(strip_html_comments(seg),
                                     source.relative_to(ROOT), (source.resolve(),)))
        else:
            parts.append(seg)
    return GENERATED_HEADER.format(source=source.relative_to(ROOT)) + "".join(parts)


def build_config_file(source: Path) -> str:
    """Expand a config-tree source file (src/opencode/*).

    Markdown files get include expansion but NO generated header (agents/*.md
    must start with their frontmatter; AGENTS.md feeds the system prompt).
    HTML comments are stripped pre-expansion, like every other tree — opencode
    injects AGENTS.md verbatim into the LLM context, so only instructions may
    reach it.
    Non-markdown files (opencode.jsonc, plugins, patches) are copied verbatim.
    """
    if source.suffix == ".md":
        text = normalize_markdown(source.read_text(encoding="utf-8"),
                                  fix_indent=False)
        parts: list[str] = []
        for kind, seg in split_segments(text):
            if kind == "text":
                parts.append(expand_text(strip_html_comments(seg),
                                         source.relative_to(ROOT), (source.resolve(),)))
            else:
                parts.append(seg)
        return "".join(parts)
    return source.read_text(encoding="utf-8")


def collect_prompt_sources() -> list[Path]:
    """All buildable prompt source files (scenario prompts under src/), sorted.

    Fundamentals fragments (`src/fundamentals/`) and the config tree
    (`src/opencode/`) are excluded — they exist to be pulled in via
    {{include:...}} / built as a config tree, never as standalone prompts.
    """
    if not SRC.is_dir():
        return []
    return sorted(
        p for p in SRC.rglob("*.md")
        if FUNDAMENTALS not in p.parents and CONFIG_SRC not in p.parents
    )


def collect_config_sources() -> list[Path]:
    """All config-tree source files under src/opencode/ (md + verbatim), sorted."""
    if not CONFIG_SRC.is_dir():
        return []
    return sorted(p for p in CONFIG_SRC.rglob("*") if p.is_file())


def output_for_prompt(source: Path) -> Path:
    """dist/ mirrors src/ (the 'src/' prefix is dropped, .prompt.md appended)."""
    return DIST / source.relative_to(SRC).with_suffix(".prompt.md")


def output_for_config(source: Path) -> Path:
    """dist/opencode/ mirrors src/opencode/ with exact filenames."""
    return DIST / source.relative_to(SRC)


def is_config_runtime_path(rel: Path) -> bool:
    """True when `rel` (relative to dist/opencode/) is runtime state, not output."""
    return bool(rel.parts) and rel.parts[0] in CONFIG_RUNTIME_ENTRIES


def config_orphan_candidates(out_dir: Path) -> set[Path]:
    """Files under `out_dir` that were not built — runtime state excluded."""
    if not out_dir.exists():
        return set()
    return {
        p for p in out_dir.rglob("*")
        if p.is_file() and not is_config_runtime_path(p.relative_to(out_dir))
    }


def remove_empty_parents(path: Path, stop: Path) -> None:
    """Remove now-empty directories from `path.parent` up to (not including) `stop`."""
    parent = path.parent
    while parent != stop and stop in parent.parents:
        try:
            parent.rmdir()  # only succeeds when empty
        except OSError:
            return
        parent = parent.parent


def build(sources: list[Path], config_sources: list[Path],
          only: str | None = None,
          prune: bool = False) -> tuple[list[Path], list[Path], list[Path]]:
    """Build into dist/.

    Returns (written, removed, orphans_left). Deletion is opt-in (`prune`):
    without it every orphan is reported in `orphans_left` and left untouched,
    so no user file can disappear silently.
    """
    written: list[Path] = []
    removed: list[Path] = []
    orphans_left: list[Path] = []
    built: dict[Path, str] = {}
    for source in sources:
        if only and only not in str(source.relative_to(ROOT)):
            continue
        built[source] = build_file(source)
    for source in config_sources:
        if only and only not in str(source.relative_to(ROOT)):
            continue
        built[source] = build_config_file(source)
    for source, content in built.items():
        out = output_for_config(source) if source in config_sources else output_for_prompt(source)
        needs_write = not out.exists() or out.read_text(encoding="utf-8") != content
        if needs_write:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(content, encoding="utf-8")
            written.append(out)
    if not only:
        existing = set(DIST.rglob("*.prompt.md")) if DIST.exists() else set()
        expected = {output_for_prompt(s) for s in built if s in sources}
        for orphan in sorted(existing - expected):
            if not prune:
                orphans_left.append(orphan)
                continue
            orphan.unlink()
            removed.append(orphan)
            remove_empty_parents(orphan, DIST)
        config_out = DIST / CONFIG_SRC.relative_to(SRC)
        config_expected = {output_for_config(s) for s in built if s in config_sources}
        for orphan in sorted(config_orphan_candidates(config_out) - config_expected):
            if not prune:
                orphans_left.append(orphan)
                continue
            orphan.unlink()
            removed.append(orphan)
            remove_empty_parents(orphan, config_out)
    return written, removed, orphans_left


def check(sources: list[Path], config_sources: list[Path],
          only: str | None = None) -> list[str]:
    """Report staleness as a list of problems (empty = up to date)."""
    problems: list[str] = []
    built: dict[Path, str] = {}
    for source in sources:
        if only and only not in str(source.relative_to(ROOT)):
            continue
        built[source] = build_file(source)
    for source in config_sources:
        if only and only not in str(source.relative_to(ROOT)):
            continue
        built[source] = build_config_file(source)
    for source, content in built.items():
        out = output_for_config(source) if source in config_sources else output_for_prompt(source)
        if not out.is_file():
            problems.append(f"missing: {fmt_path(out)}")
        elif out.read_text(encoding="utf-8") != content:
            problems.append(f"stale: {fmt_path(out)} (run python3 build-prompts.py)")
    if not only:
        existing = set(DIST.rglob("*.prompt.md")) if DIST.exists() else set()
        expected = {output_for_prompt(s) for s in built if s in sources}
        for orphan in sorted(existing - expected):
            problems.append(f"orphan: {fmt_path(orphan)} (source removed?)")
        config_out = DIST / CONFIG_SRC.relative_to(SRC)
        config_expected = {output_for_config(s) for s in built if s in config_sources}
        for orphan in sorted(config_orphan_candidates(config_out) - config_expected):
            problems.append(f"orphan: {fmt_path(orphan)} (source removed?)")
    return problems


def self_test() -> int:
    """Exercise the orphan-pruning policy against a throwaway tree and the real dist/.

    Guards the invariant that matters most: a symlinked ~/.config/opencode keeps
    node_modules/ and .secrets/ inside dist/opencode/, and no build may eat them.
    """
    import tempfile

    failures: list[str] = []

    def expect(condition: bool, label: str) -> None:
        if not condition:
            failures.append(label)

    # 1. Path classification.
    expect(is_config_runtime_path(Path("node_modules/pkg/index.js")),
           "nested node_modules recognised as runtime state")
    expect(is_config_runtime_path(Path(".secrets/key")),
           ".secrets recognised as runtime state")
    expect(is_config_runtime_path(Path("package-lock.json")),
           "lockfile recognised as runtime state")
    expect(not is_config_runtime_path(Path("agents/copilot.md")),
           "built output not mistaken for runtime state")

    # 2. Pruning on a throwaway tree: only orphans are candidates, and they go
    #    only when the caller prunes.
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "opencode"
        (out / "node_modules" / "pkg").mkdir(parents=True)
        (out / "node_modules" / "pkg" / "index.js").write_text("x")
        (out / ".secrets").mkdir()
        (out / ".secrets" / "key").write_text("k")
        (out / "package-lock.json").write_text("{}")
        (out / "agents").mkdir()
        (out / "agents" / "kept.md").write_text("kept")
        (out / "stale.md").write_text("stale")
        (out / "olddir").mkdir()
        (out / "olddir" / "orphan.md").write_text("orphan")

        expected = {out / "agents" / "kept.md"}
        candidates = sorted(config_orphan_candidates(out) - expected)
        expect(candidates == [out / "olddir" / "orphan.md", out / "stale.md"],
               f"candidates are exactly the built orphans (got {candidates})")

        for orphan in candidates:
            orphan.unlink()
            remove_empty_parents(orphan, out)
        expect(not (out / "stale.md").exists(), "prune removes the orphan")
        expect(not (out / "olddir").exists(), "prune removes the emptied directory")
        expect((out / "node_modules" / "pkg" / "index.js").exists(),
               "prune keeps node_modules")
        expect((out / ".secrets" / "key").exists(), "prune keeps .secrets")
        expect((out / "package-lock.json").exists(), "prune keeps the lockfile")
        expect((out / "agents" / "kept.md").exists(), "prune keeps expected output")

    # 3. Integration: a real non-pruning build neither deletes nor reports the
    #    runtime probes it finds in dist/opencode/.
    config_out = DIST / CONFIG_SRC.relative_to(SRC)
    probes = [config_out / "node_modules" / ".self-test" / "probe.js",
              config_out / ".secrets" / ".self-test-key"]
    try:
        for probe in probes:
            probe.parent.mkdir(parents=True, exist_ok=True)
            probe.write_text("probe")
        _, removed, orphans_left = build(collect_prompt_sources(),
                                         collect_config_sources(), prune=False)
        expect(all(probe.exists() for probe in probes),
               "build left the runtime probes in place")
        expect(not any(p in probes for p in removed), "build removed no probe")
        expect(not any(p in probes for p in orphans_left),
               "build reported no runtime probe as an orphan")
    finally:
        for probe in probes:
            probe.unlink(missing_ok=True)
        # rmdir (never rmtree) from the deepest level up, so a real .secrets/
        # directory can never be lost and a pre-existing node_modules stays.
        for parent in [config_out / "node_modules" / ".self-test",
                       config_out / "node_modules",
                       config_out / ".secrets"]:
            try:
                parent.rmdir()
            except OSError:
                pass  # not empty — it holds the user's own files

    if failures:
        print("self-test FAILED:", file=sys.stderr)
        for failure in failures:
            print(f"  - {failure}", file=sys.stderr)
        return 1
    print("self-test OK — runtime state is never pruned.")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Expand {{include:...}} directives into flat prompts in dist/. "
            "Include paths are relative to fundamentals/."
        ),
        epilog=(
            "Examples:\n"
            "  python3 build-prompts.py                rebuild all prompts\n"
            "  python3 build-prompts.py --check        verify dist/ is up to date\n"
            "  python3 build-prompts.py --prune        also delete orphaned dist/ files\n"
            "  python3 build-prompts.py --self-test    check the pruning policy\n"
            "  python3 build-prompts.py -f Help        rebuild only matching files\n"
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--check", action="store_true",
                        help="verify dist/ is up to date; exit 1 if not")
    parser.add_argument("--prune", action="store_true",
                        help="delete dist/ files whose source is gone (default: warn only)")
    parser.add_argument("--self-test", action="store_true",
                        help="verify that runtime state in dist/opencode/ is never pruned")
    parser.add_argument("-f", "--file", metavar="SUBSTR", default=None,
                        help="only build source files whose relative path contains SUBSTR")
    args = parser.parse_args(argv)

    if args.self_test:
        return self_test()

    try:
        sources = collect_prompt_sources()
        config_sources = collect_config_sources()
        if args.check:
            problems = check(sources, config_sources, only=args.file)
            if problems:
                print("dist/ is OUT OF DATE:", file=sys.stderr)
                for p in problems:
                    print(f"  - {p}", file=sys.stderr)
                return 1
            print("dist/ is up to date.")
            return 0
        written, removed, orphans_left = build(sources, config_sources,
                                               only=args.file, prune=args.prune)
        for w in written:
            print(f"wrote {fmt_path(w)}")
        for r in removed:
            print(f"removed {fmt_path(r)}")
        if orphans_left:
            print("warning: orphaned files left in dist/ (source removed?):",
                  file=sys.stderr)
            for orphan in orphans_left:
                print(f"  - {fmt_path(orphan)}  (run with --prune to delete)",
                      file=sys.stderr)
        if not written and not removed and not orphans_left:
            print("nothing to do — dist/ is up to date.")
        return 0
    except BuildError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
